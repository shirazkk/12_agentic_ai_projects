"""
llm_client.py: Pluggable LLM Client Interface

Supports:
1. OpenRouterLLMClient: Connects to OpenRouter (default model: nvidia/nemotron-3-super-120b-a12b:free)
   Configured flexibly via .env or constructor parameters.
2. MockLLMClient: Simulates scripted LLM responses for deterministic, fast, offline unit tests.
"""

import os
from abc import ABC, abstractmethod
from typing import Any, Dict, List, Optional
from pathlib import Path
from dotenv import load_dotenv

# Look for .env in current directory or package directory
load_dotenv()
_pkg_env = Path(__file__).resolve().parent / ".env"
if _pkg_env.exists():
    load_dotenv(dotenv_path=_pkg_env)
_root_env = Path(__file__).resolve().parent.parent / ".env"
if _root_env.exists():
    load_dotenv(dotenv_path=_root_env)


class BaseLLMClient(ABC):
    """Abstract Base Class for LLM providers."""

    @abstractmethod
    def generate(
        self,
        prompt: str,
        system_prompt: Optional[str] = None,
        image_url: Optional[str] = None,
    ) -> str:
        """
        Send a prompt to the LLM and return its raw string response.
        
        Args:
            prompt: The user query or task instructions.
            system_prompt: Optional system-level instructions or constraints.
            image_url: Optional data URL or public URL for vision/multimodal extraction.

        Returns:
            The raw text generated by the model.
        """
        pass


class OpenRouterLLMClient(BaseLLMClient):
    """
    OpenRouter client using the OpenAI-compatible API.
    
    Reads credentials and model configuration from .env:
    - OPENROUTER_API_KEY
    - OPENROUTER_MODEL (defaults to nvidia/nemotron-3-super-120b-a12b:free)
    - OPENROUTER_BASE_URL (defaults to https://openrouter.ai/api/v1)
    """

    def __init__(
        self,
        api_key: Optional[str] = None,
        model: Optional[str] = None,
        base_url: Optional[str] = None,
        temperature: float = 0.1,
    ):
        """
        Initialize the OpenRouter LLM client.
        
        Args:
            api_key: OpenRouter API key. If not provided, reads OPENROUTER_API_KEY from .env.
            model: Model name. If not provided, reads OPENROUTER_MODEL from .env.
            base_url: Base URL for OpenRouter API. Defaults to https://openrouter.ai/api/v1.
            temperature: Sampling temperature (0.1 for high determinism in structured extraction).
        """
        self.api_key = api_key or os.getenv("OPENROUTER_API_KEY")
        self.model = model or os.getenv("OPENROUTER_MODEL", "nvidia/nemotron-3-super-120b-a12b:free")
        self.base_url = base_url or os.getenv("OPENROUTER_BASE_URL", "https://openrouter.ai/api/v1")
        self.temperature = temperature

        # Lazy import of openai and httpx
        try:
            import httpx
            from openai import OpenAI
            # Passing explicit http_client avoids httpx 0.28+ 'proxies' incompatibility in older openai sdk
            custom_http_client = httpx.Client()
            self._client = OpenAI(
                api_key=self.api_key or "missing-key",
                base_url=self.base_url,
                http_client=custom_http_client,
                default_headers={
                    "HTTP-Referer": "https://github.com/agentic-ai-projects",
                    "X-Title": "Structured Output Agent",
                },
            )
        except ImportError as e:
            raise ImportError(
                "The 'openai' and 'httpx' packages are required to use OpenRouterLLMClient. "
                "Install them using: pip install openai httpx"
            ) from e

    def generate(
        self,
        prompt: str,
        system_prompt: Optional[str] = None,
        image_url: Optional[str] = None,
    ) -> str:
        """
        Call OpenRouter model and return raw generated completion text.
        Supports both text prompts and multimodal vision input.
        """
        if not self.api_key or self.api_key == "your_openrouter_api_key_here":
            raise ValueError(
                "OpenRouter API key is missing. Please set OPENROUTER_API_KEY in your .env file "
                "or pass it directly to OpenRouterLLMClient(api_key='...')."
            )

        messages = []
        if system_prompt:
            messages.append({"role": "system", "content": system_prompt})

        if image_url:
            user_content = [
                {"type": "text", "text": prompt},
                {"type": "image_url", "image_url": {"url": image_url}},
            ]
        else:
            user_content = prompt

        messages.append({"role": "user", "content": user_content})

        response = self._client.chat.completions.create(
            model=self.model,
            messages=messages,
            temperature=self.temperature,
        )

        choices = getattr(response, "choices", None)
        if not choices or len(choices) == 0:
            error_msg = getattr(response, "error", None) or "The model provider returned no choices (temporary rate limit or provider timeout)."
            raise RuntimeError(f"OpenRouter Provider Error: {error_msg}")

        choice = choices[0]
        content = getattr(choice.message, "content", "") or ""

        # Support reasoning models (e.g. nemotron-nano-omni-reasoning)
        if not content.strip() and hasattr(choice.message, "reasoning") and choice.message.reasoning:
            content = choice.message.reasoning

        return content or ""


class MockLLMClient(BaseLLMClient):
    """
    Mock LLM client for automated testing and local experiments.
    
    Allows feeding an ordered list of scripted responses so we can simulate:
    - 1st attempt: bad JSON or schema violation
    - 2nd attempt: self-corrected valid JSON
    - All attempts failing (to test retry exhaustion)
    """

    def __init__(self, responses: Optional[List[str]] = None):
        """
        Args:
            responses: Sequence of raw strings to return across consecutive generate() calls.
        """
        self.responses: List[str] = list(responses or [])
        self.call_history: List[Dict[str, Any]] = []

    def set_responses(self, responses: List[str]) -> None:
        """Update or reset the queue of scripted responses."""
        self.responses = list(responses)

    def generate(
        self,
        prompt: str,
        system_prompt: Optional[str] = None,
        image_url: Optional[str] = None,
    ) -> str:
        """
        Return the next scripted response in queue, while logging prompt history.
        """
        self.call_history.append({
            "prompt": prompt,
            "system_prompt": system_prompt,
            "image_url": image_url,
        })

        if not self.responses:
            raise IndexError("MockLLMClient has no more scripted responses available.")

        # Pop the first response from the list (FIFO queue)
        return self.responses.pop(0)


def create_llm_client(use_mock: bool = False, mock_responses: Optional[List[str]] = None) -> BaseLLMClient:
    """
    Convenience factory to create an LLM client.
    
    Args:
        use_mock: If True, returns a MockLLMClient with mock_responses.
        mock_responses: List of strings for the Mock client.

    Returns:
        BaseLLMClient instance.
    """
    if use_mock:
        return MockLLMClient(responses=mock_responses)
    return OpenRouterLLMClient()
